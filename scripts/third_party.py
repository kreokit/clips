#!/usr/bin/env python3
"""Regenerates THIRD-PARTY-LICENSES.md from its hand-written header plus the Rust crates
(`cargo metadata`, normal and build dependencies of the app) and the production npm
packages (`pnpm licenses list --prod`).

    python3 scripts/third_party.py          # rewrite the file
    python3 scripts/third_party.py --check  # CI: fail if the file is out of date
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "scripts" / "third-party-header.md"
OUTPUT = ROOT / "THIRD-PARTY-LICENSES.md"


def rust_crates() -> list[tuple[str, str, str, str]]:
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT / "src-tauri", capture_output=True, text=True, check=True,
    ).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        node = stack.pop()
        if node in seen:
            continue
        seen.add(node)
        for dep in nodes[node]["deps"]:
            if any(kind["kind"] in (None, "build") for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    seen.discard(root)
    rows = []
    for node in seen:
        p = packages[node]
        rows.append((p["name"], p["version"], p.get("license") or "see repository", p.get("repository") or ""))
    return sorted(rows)


def npm_packages() -> list[tuple[str, str, str, str]]:
    out = subprocess.run(
        ["pnpm", "licenses", "list", "--prod", "--json"],
        cwd=ROOT, capture_output=True, text=True, check=True, shell=sys.platform == "win32",
    ).stdout
    rows = []
    for license_name, packages in json.loads(out).items():
        for p in packages:
            rows.append((p["name"], ", ".join(p["versions"]), license_name, p.get("homepage") or ""))
    return sorted(rows)


def table(rows: list[tuple[str, str, str, str]]) -> str:
    lines = ["| Package | Version | Licence | Source |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {l} | {s} |" for n, v, l, s in rows]
    return "\n".join(lines)


def render() -> str:
    return (
        HEADER.read_text()
        + "\n## Rust crates\n\nCompiled into the app (generated by scripts/third_party.py).\n\n"
        + table(rust_crates())
        + "\n\n## npm packages\n\nBundled into the app's interface (generated by scripts/third_party.py).\n\n"
        + table(npm_packages())
        + "\n"
    )


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit("THIRD-PARTY-LICENSES.md is out of date: run python3 scripts/third_party.py")
        print("THIRD-PARTY-LICENSES.md is up to date")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.name}")


if __name__ == "__main__":
    main()
